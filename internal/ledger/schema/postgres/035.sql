-- Who a firing reached, worked out (docs/design/routing.md, "In lapilli
-- serve"), as SQLite's 035.sql: what each table and column is for is said
-- there.
CREATE TABLE routed (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	at BIGINT NOT NULL,
	receiver TEXT COLLATE "C" NOT NULL,
	kind TEXT COLLATE "C" NOT NULL,
	page BIGINT NOT NULL DEFAULT 0,
	reason TEXT COLLATE "C" NOT NULL,
	grp TEXT COLLATE "C" NOT NULL DEFAULT '',
	firings BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX routed_at ON routed (at);

CREATE TABLE firing_routed (
	firing_id BIGINT NOT NULL PRIMARY KEY REFERENCES firings (id) ON DELETE CASCADE,
	notified BIGINT NOT NULL DEFAULT 0,
	paged BIGINT NOT NULL DEFAULT 0,
	first_page BIGINT NOT NULL DEFAULT 0,
	grouped BIGINT NOT NULL DEFAULT 0,
	page_ats TEXT COLLATE "C" NOT NULL DEFAULT '[]',
	receivers TEXT COLLATE "C" NOT NULL DEFAULT '[]',
	muted TEXT COLLATE "C" NOT NULL DEFAULT '[]'
);

-- The notifications that told of each firing (as in the SQLite file).
CREATE TABLE firing_routed_sent (
	firing_id BIGINT NOT NULL REFERENCES firings (id) ON DELETE CASCADE,
	at BIGINT NOT NULL,
	receiver TEXT COLLATE "C" NOT NULL,
	kind TEXT COLLATE "C" NOT NULL,
	page BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX firing_routed_sent_firing ON firing_routed_sent (firing_id, at);
CREATE INDEX firing_routed_sent_at ON firing_routed_sent (at);

-- Which hours were worked out (as in the SQLite file).
CREATE TABLE routed_cover (
	from_at BIGINT NOT NULL PRIMARY KEY,
	to_at BIGINT NOT NULL,
	ok BIGINT NOT NULL DEFAULT 1,
	why TEXT COLLATE "C" NOT NULL DEFAULT ''
);
