-- Goals (docs/design/goals.md), as SQLite's 020.sql: what each column is
-- for is said there.
CREATE TABLE goals (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT COLLATE "C" NOT NULL,
	team_id BIGINT NOT NULL DEFAULT 0,
	every_team BIGINT NOT NULL DEFAULT 0,
	measure TEXT COLLATE "C" NOT NULL,
	at_least TEXT COLLATE "C" NOT NULL DEFAULT '',
	at_most TEXT COLLATE "C" NOT NULL DEFAULT '',
	no_worse_than TEXT COLLATE "C" NOT NULL DEFAULT '',
	slack TEXT COLLATE "C" NOT NULL DEFAULT '',
	critical TEXT COLLATE "C" NOT NULL DEFAULT '[]',
	each TEXT COLLATE "C" NOT NULL DEFAULT 'week',
	declared BIGINT NOT NULL DEFAULT 1,
	updated BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX goals_name ON goals (name);

ALTER TABLE tasks ADD COLUMN goal TEXT COLLATE "C" NOT NULL DEFAULT '';
CREATE INDEX tasks_goal ON tasks (goal, status) WHERE goal != '';
