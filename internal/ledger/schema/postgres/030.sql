-- Rules left out of a source's copies (docs/design/grafanajudged.md), as
-- SQLite's 030.sql: what each column is for is said there. A rule's name
-- is 512 characters at most where it is taken in, and a source's 40, so
-- (source, rule, from_at) is a btree.
CREATE TABLE left_out (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	source TEXT COLLATE "C" NOT NULL,
	rule TEXT COLLATE "C" NOT NULL,
	from_at BIGINT NOT NULL,
	to_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX left_out_rule ON left_out (source, rule, from_at);
CREATE INDEX left_out_to ON left_out (to_at);
