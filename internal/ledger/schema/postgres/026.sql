-- A person's verdict on one firing, and rules judged by nothing
-- (docs/design/judging.md, item 3), as SQLite's 026.sql: what each table
-- and column is for is said there.
CREATE TABLE verdicts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	series_id BIGINT NOT NULL REFERENCES series (id),
	start_at BIGINT NOT NULL,
	end_at BIGINT,
	unrelated TEXT COLLATE "C" NOT NULL DEFAULT '[]',
	unrelated_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	unrelated_at BIGINT NOT NULL DEFAULT 0,
	unrelated_note TEXT COLLATE "C" NOT NULL DEFAULT '',
	action TEXT COLLATE "C" NOT NULL DEFAULT '',
	action_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	action_at BIGINT NOT NULL DEFAULT 0,
	action_note TEXT COLLATE "C" NOT NULL DEFAULT '',
	moved TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX verdicts_firing ON verdicts (series_id, start_at);
CREATE INDEX verdicts_start ON verdicts (start_at);

