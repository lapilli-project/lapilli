-- Marked windows (docs/design/marked.md), as SQLite's 021.sql: what each
-- table and column is for is said there.
CREATE TABLE marked_kinds (
	id BIGINT PRIMARY KEY,
	name TEXT COLLATE "C" NOT NULL UNIQUE
);

CREATE TABLE marked (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	kind_id BIGINT NOT NULL REFERENCES marked_kinds (id),
	origin TEXT COLLATE "C" NOT NULL,
	title TEXT COLLATE "C" NOT NULL,
	start_at BIGINT NOT NULL,
	end_at BIGINT NOT NULL,
	every TEXT COLLATE "C" NOT NULL DEFAULT '',
	repeat_on TEXT COLLATE "C" NOT NULL DEFAULT '',
	until_at BIGINT,
	team_id BIGINT NOT NULL DEFAULT 0,
	labels TEXT COLLATE "C" NOT NULL DEFAULT '{}',
	declared BIGINT NOT NULL DEFAULT 0,
	given_back BIGINT NOT NULL DEFAULT 0,
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX marked_start ON marked (start_at);
CREATE INDEX marked_every ON marked (every, start_at);

ALTER TABLE firings ADD COLUMN marked BIGINT NOT NULL DEFAULT 0;

CREATE TABLE marked_days (
	day BIGINT NOT NULL,
	rule_id BIGINT NOT NULL,
	kind_id BIGINT NOT NULL,
	firings BIGINT NOT NULL,
	white BIGINT NOT NULL,
	refired BIGINT NOT NULL,
	PRIMARY KEY (day, rule_id, kind_id)
);
CREATE TABLE marked_weeks (
	week BIGINT NOT NULL,
	rule_id BIGINT NOT NULL,
	kind_id BIGINT NOT NULL,
	firings BIGINT NOT NULL,
	white BIGINT NOT NULL,
	refired BIGINT NOT NULL,
	PRIMARY KEY (week, rule_id, kind_id)
);
