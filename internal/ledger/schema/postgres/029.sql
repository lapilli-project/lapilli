-- Mutes (docs/design/mutes.md), as SQLite's 029.sql: what each column is
-- for is said there. A rule's name is 512 characters at most where it is
-- taken in, as notified's is, so (rule, hour) is a btree.
CREATE TABLE mutes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	key TEXT COLLATE "C" NOT NULL,
	hour BIGINT NOT NULL,
	rule TEXT COLLATE "C" NOT NULL,
	labels TEXT COLLATE "C" NOT NULL,
	kind TEXT COLLATE "C" NOT NULL,
	ref TEXT COLLATE "C" NOT NULL DEFAULT '',
	first_at BIGINT NOT NULL,
	last_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX mutes_key ON mutes (key, hour);
CREATE INDEX mutes_rule ON mutes (rule, hour);
CREATE INDEX mutes_last ON mutes (last_at);
