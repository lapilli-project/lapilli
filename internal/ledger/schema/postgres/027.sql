-- What checking each rule's expectations found (docs/design/expectations.md,
-- steps 2 and 4), as SQLite's 027.sql: what each column is for is said there. A
-- rule's name can be longer than a btree holds: SQLite's PRIMARY KEY
-- (rule, expect, week) is a unique index on (md5(rule), expect, week), as
-- checked's is (017.sql).
CREATE TABLE expectation_checks (
	rule TEXT COLLATE "C" NOT NULL,
	expect TEXT COLLATE "C" NOT NULL,
	week BIGINT NOT NULL,
	what TEXT COLLATE "C" NOT NULL,
	held TEXT COLLATE "C" NOT NULL,
	selector TEXT COLLATE "C" NOT NULL,
	source TEXT COLLATE "C" NOT NULL,
	result TEXT COLLATE "C" NOT NULL,
	why TEXT COLLATE "C" NOT NULL DEFAULT '',
	n BIGINT,
	value TEXT COLLATE "C" NOT NULL DEFAULT '',
	at BIGINT NOT NULL DEFAULT 0,
	version TEXT COLLATE "C" NOT NULL DEFAULT '',
	detail TEXT COLLATE "C" NOT NULL DEFAULT '',
	current BIGINT NOT NULL DEFAULT 1,
	checked BIGINT NOT NULL,
	told BIGINT NOT NULL DEFAULT 0,
	task BIGINT NOT NULL DEFAULT 0,
	tasked BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX expectation_checks_key ON expectation_checks (md5(rule), expect, week);
CREATE INDEX expectation_checks_result ON expectation_checks (result, week);

-- Drafts of what a rule is held to (docs/design/expectations.md, step 3),
-- as SQLite's 027.sql: what each column is for is said there. A rule's
-- name can be longer than a btree holds: SQLite's index on (rule, id) is
-- one on (md5(rule), id). made_by is a person's name, bounded where it is
-- taken in, as proposals' is.
CREATE TABLE expectation_drafts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	rule TEXT COLLATE "C" NOT NULL,
	origin TEXT COLLATE "C" NOT NULL,
	made_by TEXT COLLATE "C" NOT NULL,
	agent BIGINT NOT NULL DEFAULT 0,
	made BIGINT NOT NULL,
	text TEXT COLLATE "C" NOT NULL,
	tests TEXT COLLATE "C" NOT NULL DEFAULT '{}',
	reason TEXT COLLATE "C" NOT NULL DEFAULT '',
	found TEXT COLLATE "C" NOT NULL DEFAULT '[]',
	target TEXT COLLATE "C" NOT NULL,
	doc_hash TEXT COLLATE "C" NOT NULL DEFAULT '',
	document TEXT COLLATE "C" NOT NULL DEFAULT '',
	state TEXT COLLATE "C" NOT NULL,
	decided_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	decided BIGINT NOT NULL DEFAULT 0,
	pr TEXT COLLATE "C" NOT NULL DEFAULT '',
	link TEXT COLLATE "C" NOT NULL DEFAULT '',
	pr_reason TEXT COLLATE "C" NOT NULL DEFAULT '',
	proposal BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX expectation_drafts_rule ON expectation_drafts (md5(rule), id);
CREATE INDEX expectation_drafts_by ON expectation_drafts (made_by, made);
CREATE INDEX expectation_drafts_state ON expectation_drafts (state, id);
CREATE INDEX expectation_drafts_pr ON expectation_drafts (pr, id);

-- What a proposal adding a rule holds the rule to, as SQLite's 027.sql.
ALTER TABLE proposals ADD COLUMN expect TEXT COLLATE "C" NOT NULL DEFAULT '';
