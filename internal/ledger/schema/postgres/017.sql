-- The ledger in Postgres (docs/design/postgres.md), as SQLite's schema/001.sql
-- to 017.sql leave it, in one file: a Postgres ledger starts at schema 17.
-- What each table and column is for is said there; here is what differs.
--
-- Every integer is a BIGINT, as SQLite's are 64 bits. Every text is
-- COLLATE "C": compared and sorted byte by byte, as SQLite compares them,
-- whatever the database's own collation; lower(), upper() and ILIKE change
-- ASCII letters alone, as SQLite's lower(), upper() and LIKE do. A row's id
-- is an identity column, never given again, a deleted row's included, as
-- AUTOINCREMENT keeps SQLite's for tasks and comments. A label set is kept
-- unique by its md5 beside the text, as an index holds a value of some 2,700
-- bytes at most and a label set can be longer.

CREATE TABLE meta (key TEXT COLLATE "C" PRIMARY KEY, value TEXT COLLATE "C" NOT NULL);

CREATE TABLE docs (hash TEXT COLLATE "C" PRIMARY KEY, data BYTEA NOT NULL);

CREATE TABLE versions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	since BIGINT NOT NULL,
	digest TEXT COLLATE "C" NOT NULL,
	docs TEXT COLLATE "C" NOT NULL,
	names TEXT COLLATE "C" NOT NULL
);
CREATE INDEX versions_since ON versions (since);

CREATE TABLE rules (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT COLLATE "C" NOT NULL UNIQUE,
	grp TEXT COLLATE "C" NOT NULL DEFAULT '',
	severity TEXT COLLATE "C" NOT NULL DEFAULT '',
	unsupported TEXT COLLATE "C" NOT NULL DEFAULT '',
	source TEXT COLLATE "C" NOT NULL DEFAULT '',
	sent TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX rules_recorded ON rules (source, sent, severity) WHERE source != '';

CREATE TABLE series (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	rule_id BIGINT NOT NULL REFERENCES rules (id),
	labels TEXT COLLATE "C" NOT NULL
);
CREATE UNIQUE INDEX series_labels ON series (rule_id, md5(labels));
CREATE INDEX series_alarm ON series (((labels::jsonb ->> 'alarm_id') COLLATE "C"))
	WHERE (labels::jsonb ->> 'alarm_id') IS NOT NULL;

CREATE TABLE firings (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	series_id BIGINT NOT NULL REFERENCES series (id),
	rule_id BIGINT NOT NULL,
	start_at BIGINT NOT NULL,
	end_at BIGINT,
	day BIGINT NOT NULL,
	white BIGINT NOT NULL DEFAULT 0,
	refired BIGINT NOT NULL DEFAULT 0,
	excused BIGINT NOT NULL DEFAULT 0,
	deploy BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX firings_start ON firings (start_at);
CREATE INDEX firings_rule ON firings (rule_id, start_at);
CREATE INDEX firings_series ON firings (series_id, start_at);
CREATE INDEX firings_open ON firings (start_at) WHERE end_at IS NULL;
CREATE INDEX firings_refired ON firings (rule_id, start_at) WHERE refired = 1;

CREATE TABLE incidents (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	key TEXT COLLATE "C" NOT NULL UNIQUE,
	origin TEXT COLLATE "C" NOT NULL,
	state TEXT COLLATE "C" NOT NULL DEFAULT '',
	counts BIGINT NOT NULL DEFAULT 1,
	title TEXT COLLATE "C" NOT NULL DEFAULT '',
	start_at BIGINT NOT NULL,
	end_at BIGINT,
	labels TEXT COLLATE "C" NOT NULL DEFAULT '{}',
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX incidents_start ON incidents (start_at);

CREATE TABLE catches (
	incident_id BIGINT NOT NULL,
	rule_id BIGINT NOT NULL,
	delay BIGINT NOT NULL,
	PRIMARY KEY (incident_id, rule_id)
);
CREATE INDEX catches_rule ON catches (rule_id);

CREATE TABLE days (
	day BIGINT NOT NULL,
	rule_id BIGINT NOT NULL,
	firings BIGINT NOT NULL,
	white BIGINT NOT NULL,
	refired BIGINT NOT NULL,
	excused BIGINT NOT NULL DEFAULT 0,
	deploy BIGINT NOT NULL DEFAULT 0,
	deploy_white BIGINT NOT NULL DEFAULT 0,
	PRIMARY KEY (day, rule_id)
);
CREATE INDEX days_rule ON days (rule_id, day);
CREATE TABLE weeks (
	week BIGINT NOT NULL,
	rule_id BIGINT NOT NULL,
	firings BIGINT NOT NULL,
	white BIGINT NOT NULL,
	refired BIGINT NOT NULL,
	excused BIGINT NOT NULL DEFAULT 0,
	deploy BIGINT NOT NULL DEFAULT 0,
	deploy_white BIGINT NOT NULL DEFAULT 0,
	PRIMARY KEY (week, rule_id)
);

CREATE TABLE runs (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	kind TEXT COLLATE "C" NOT NULL,
	started BIGINT NOT NULL,
	finished BIGINT NOT NULL,
	period_from BIGINT NOT NULL DEFAULT 0,
	period_to BIGINT NOT NULL DEFAULT 0,
	firings BIGINT NOT NULL DEFAULT 0,
	failed TEXT COLLATE "C" NOT NULL DEFAULT '{}',
	error TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX runs_started ON runs (started);

CREATE TABLE settings (
	key TEXT COLLATE "C" PRIMARY KEY,
	value TEXT COLLATE "C" NOT NULL,
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL
);

CREATE TABLE changes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	at BIGINT NOT NULL,
	by TEXT COLLATE "C" NOT NULL,
	what TEXT COLLATE "C" NOT NULL,
	before TEXT COLLATE "C" NOT NULL DEFAULT '',
	after TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX changes_at ON changes (at);
CREATE INDEX changes_what ON changes (what, id);

CREATE TABLE results (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	kind TEXT COLLATE "C" NOT NULL,
	at BIGINT NOT NULL,
	period_from BIGINT NOT NULL,
	period_to BIGINT NOT NULL,
	body BYTEA NOT NULL
);
CREATE INDEX results_kind ON results (kind, at);

CREATE TABLE teams (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT COLLATE "C" NOT NULL UNIQUE,
	rules TEXT COLLATE "C" NOT NULL DEFAULT '',
	labels TEXT COLLATE "C" NOT NULL DEFAULT '{}',
	note TEXT COLLATE "C" NOT NULL DEFAULT '',
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	work_hours TEXT COLLATE "C" NOT NULL DEFAULT '',
	sleep_hours TEXT COLLATE "C" NOT NULL DEFAULT '',
	tz TEXT COLLATE "C" NOT NULL DEFAULT '',
	shifts TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE notes (
	rule TEXT COLLATE "C" PRIMARY KEY,
	team_id BIGINT REFERENCES teams (id) ON DELETE SET NULL,
	status TEXT COLLATE "C" NOT NULL DEFAULT '',
	runbook TEXT COLLATE "C" NOT NULL DEFAULT '',
	note TEXT COLLATE "C" NOT NULL DEFAULT '',
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE windows (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title TEXT COLLATE "C" NOT NULL,
	start_at BIGINT NOT NULL,
	end_at BIGINT NOT NULL,
	rules TEXT COLLATE "C" NOT NULL DEFAULT '',
	labels TEXT COLLATE "C" NOT NULL DEFAULT '{}',
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	every TEXT COLLATE "C" NOT NULL DEFAULT '',
	until_at BIGINT,
	team_id BIGINT NOT NULL DEFAULT 0,
	repeat_on TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX windows_start ON windows (start_at);
CREATE INDEX windows_every ON windows (every, start_at);

CREATE TABLE tasks (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title TEXT COLLATE "C" NOT NULL,
	kind TEXT COLLATE "C" NOT NULL DEFAULT '',
	rule TEXT COLLATE "C" NOT NULL DEFAULT '',
	incident TEXT COLLATE "C" NOT NULL DEFAULT '',
	team_id BIGINT REFERENCES teams (id) ON DELETE SET NULL,
	assignee TEXT COLLATE "C" NOT NULL DEFAULT '',
	status TEXT COLLATE "C" NOT NULL DEFAULT 'open',
	due BIGINT,
	body TEXT COLLATE "C" NOT NULL DEFAULT '',
	created BIGINT NOT NULL,
	created_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	link TEXT COLLATE "C" NOT NULL DEFAULT '',
	overdue_told BIGINT,
	done_at BIGINT
);
CREATE INDEX tasks_open ON tasks (status, updated);
CREATE INDEX tasks_rule ON tasks (rule);
CREATE INDEX tasks_incident ON tasks (incident);

CREATE TABLE comments (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	on_kind TEXT COLLATE "C" NOT NULL,
	on_key TEXT COLLATE "C" NOT NULL,
	body TEXT COLLATE "C" NOT NULL,
	created BIGINT NOT NULL,
	created_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	updated BIGINT NOT NULL,
	origin TEXT COLLATE "C" NOT NULL DEFAULT '',
	ref TEXT COLLATE "C" NOT NULL DEFAULT '',
	author TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX comments_on ON comments (on_kind, on_key, created);
CREATE UNIQUE INDEX comments_ref ON comments (on_kind, on_key, ref) WHERE ref != '';

CREATE TABLE outbox (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	dest TEXT COLLATE "C" NOT NULL,
	event TEXT COLLATE "C" NOT NULL,
	body TEXT COLLATE "C" NOT NULL,
	created BIGINT NOT NULL,
	attempts BIGINT NOT NULL DEFAULT 0,
	next_at BIGINT NOT NULL,
	sent_at BIGINT,
	error TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX outbox_due ON outbox (dest, sent_at, next_at);

CREATE TABLE sources (
	name TEXT COLLATE "C" PRIMARY KEY,
	written BIGINT NOT NULL,
	written_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	period_from BIGINT NOT NULL,
	period_to BIGINT NOT NULL,
	firings BIGINT NOT NULL DEFAULT 0,
	changed BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE notifications (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	at BIGINT NOT NULL,
	source TEXT COLLATE "C" NOT NULL,
	receiver TEXT COLLATE "C" NOT NULL DEFAULT '',
	grp TEXT COLLATE "C" NOT NULL DEFAULT '',
	reason TEXT COLLATE "C" NOT NULL,
	resolved BIGINT NOT NULL DEFAULT 0,
	digest TEXT COLLATE "C" NOT NULL,
	msg TEXT COLLATE "C" NOT NULL DEFAULT '',
	copied TEXT COLLATE "C" NOT NULL DEFAULT '',
	shape TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX notifications_at ON notifications (at);
CREATE INDEX notifications_same ON notifications (digest, at);
CREATE INDEX notifications_group ON notifications (source, receiver, grp, at);
CREATE INDEX notifications_msg ON notifications (msg) WHERE msg != '';

CREATE TABLE notified (
	notification_id BIGINT NOT NULL REFERENCES notifications (id) ON DELETE CASCADE,
	rule TEXT COLLATE "C" NOT NULL,
	labels TEXT COLLATE "C" NOT NULL,
	start_at BIGINT NOT NULL,
	firing BIGINT NOT NULL
);
CREATE INDEX notified_rule ON notified (rule, start_at);
CREATE INDEX notified_of ON notified (notification_id);
CREATE INDEX notified_alarm ON notified (((labels::jsonb ->> 'alarm_id') COLLATE "C"), start_at)
	WHERE (labels::jsonb ->> 'alarm_id') IS NOT NULL;

CREATE TABLE checked (
	rule TEXT COLLATE "C" NOT NULL,
	day BIGINT NOT NULL,
	alert TEXT COLLATE "C" NOT NULL,
	shared BIGINT NOT NULL DEFAULT 0,
	replayed BIGINT NOT NULL,
	real BIGINT NOT NULL,
	alike BIGINT NOT NULL,
	off_ms BIGINT NOT NULL,
	PRIMARY KEY (rule, day)
);
CREATE INDEX checked_day ON checked (day);

CREATE TABLE check_misses (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	rule TEXT COLLATE "C" NOT NULL,
	way TEXT COLLATE "C" NOT NULL,
	start_at BIGINT NOT NULL,
	labels TEXT COLLATE "C" NOT NULL
);
CREATE INDEX check_misses_rule ON check_misses (rule, start_at);

CREATE TABLE check_elsewhere (
	name TEXT COLLATE "C" NOT NULL,
	day BIGINT NOT NULL,
	firings BIGINT NOT NULL,
	PRIMARY KEY (name, day)
);

CREATE TABLE reports (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT COLLATE "C" NOT NULL UNIQUE,
	team_id BIGINT NOT NULL DEFAULT 0,
	schedule TEXT COLLATE "C" NOT NULL,
	span BIGINT NOT NULL DEFAULT 0,
	zone TEXT COLLATE "C" NOT NULL DEFAULT 'ledger',
	sections TEXT COLLATE "C" NOT NULL DEFAULT '[]',
	dests TEXT COLLATE "C" NOT NULL DEFAULT '[]',
	enabled BIGINT NOT NULL DEFAULT 1,
	created BIGINT NOT NULL,
	created_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	updated BIGINT NOT NULL,
	updated_by TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE proposals (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	rule TEXT COLLATE "C" NOT NULL,
	kind TEXT COLLATE "C" NOT NULL,
	path TEXT COLLATE "C" NOT NULL,
	state TEXT COLLATE "C" NOT NULL,
	made BIGINT NOT NULL,
	made_by TEXT COLLATE "C" NOT NULL,
	agent BIGINT NOT NULL DEFAULT 0,
	source TEXT COLLATE "C" NOT NULL DEFAULT '',
	doc_hash TEXT COLLATE "C" NOT NULL DEFAULT '',
	before TEXT COLLATE "C" NOT NULL,
	before_hash TEXT COLLATE "C" NOT NULL,
	after TEXT COLLATE "C" NOT NULL,
	after_hash TEXT COLLATE "C" NOT NULL DEFAULT '',
	document TEXT COLLATE "C" NOT NULL DEFAULT '',
	diff TEXT COLLATE "C" NOT NULL,
	evidence TEXT COLLATE "C" NOT NULL,
	reason TEXT COLLATE "C" NOT NULL DEFAULT '',
	link TEXT COLLATE "C" NOT NULL DEFAULT '',
	backup TEXT COLLATE "C" NOT NULL DEFAULT '',
	follows BIGINT,
	task_id BIGINT,
	updated BIGINT NOT NULL,
	applied BIGINT
);
CREATE INDEX proposals_rule ON proposals (rule, state);
CREATE INDEX proposals_state ON proposals (state, updated);

CREATE TABLE approvals (
	proposal_id BIGINT NOT NULL REFERENCES proposals (id) ON DELETE CASCADE,
	by TEXT COLLATE "C" NOT NULL,
	at BIGINT NOT NULL,
	PRIMARY KEY (proposal_id, by)
);

-- SQLite's LIKE ignores the case of ASCII letters; ILIKE over "C" does the
-- same.
CREATE TABLE grants (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	who TEXT COLLATE "C" NOT NULL CHECK (who ILIKE 'user:_%' OR who ILIKE 'group:_%'),
	role TEXT COLLATE "C" NOT NULL DEFAULT 'editor' CHECK (role = 'editor'),
	team_id BIGINT NOT NULL DEFAULT 0,
	created BIGINT NOT NULL,
	created_by TEXT COLLATE "C" NOT NULL DEFAULT '',
	UNIQUE (who, team_id)
);

CREATE TABLE on_call_turns (
	schedule TEXT COLLATE "C" NOT NULL,
	start_at BIGINT NOT NULL,
	end_at BIGINT NOT NULL,
	who TEXT COLLATE "C" NOT NULL,
	PRIMARY KEY (schedule, start_at)
);

CREATE TABLE deploy_labels (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	labels TEXT COLLATE "C" NOT NULL
);
CREATE UNIQUE INDEX deploy_labels_labels ON deploy_labels (md5(labels));
CREATE TABLE deploys (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	start_at BIGINT NOT NULL,
	end_at BIGINT NOT NULL,
	labels_id BIGINT NOT NULL REFERENCES deploy_labels (id),
	revision TEXT COLLATE "C" NOT NULL DEFAULT '',
	source TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX deploys_start ON deploys (start_at);
